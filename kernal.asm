; ****************************************************************************************************************************************
;
; Wait for the IRQ VBlank
;
; ****************************************************************************************************************************************
WaitVBlank:
                xor     a
                ld      (__VBlank),a
WaitForVBlank:
                ld      a,(__VBlank)
                and     a
                jr      z,WaitForVBlank
                ret


; ****************************************************************************************************************************************
;
; Fill memory
;
; Entry:    HL  x       (0..255)
;           DE  y       (0..191)
;           BC  color   (0..255)
;
; ****************************************************************************************************************************************
memset:         ld      (hl),e
                ld      d,h
                ld      e,l
                inc     de
                ldir
                ret

; ****************************************************************************************************************************************
;
; Copy memory
;
; Entry:    HL  src     (0..255)
;           DE  dest    (0..191)
;           BC  count   (0..255)
;
; ****************************************************************************************************************************************
memcpy:         ld      a,b
                or      c
                and     a
                jr      z,Skip
                ldir
Skip:           ret



; ****************************************************************************************************************************************
;       DebugPrint(string)
; ****************************************************************************************************************************************
DebugPrint:
        ld      hl,0
        add     hl,sp           ; get stack
        inc     hl              ; skip return address
        inc     hl

        ld      b,(hl)          ; get string lengh
        inc     hl
        ld      de,StringBuffer ; get temp buffer
loopStr:
        ld      a,(hl)          ; copy string
        ld      (de),a
        inc     hl
        inc     de
        djnz    loopStr

        xor     a
        ld      (de),a          ; stick a ,0 at the end

    ;NextReg $50,$ff            ; set ROM
        ld      hl,StringBuffer
        rst     $18             ; CSpect DEBUG PRINT extension 
        nop
        ret


; ******************************************************************************
; Function: Scan the whole keyboard
; ******************************************************************************
ReadKeyboard:
        ld  b,39
        ld  hl,Keys
        xor a
@lp1:   ld  (hl),a
        inc hl
        djnz    @lp1

        ld  iy,Keys
        ld  bc,$fefe            ; Caps,Z,X,C,V
        ld  hl,RawKeys
@ReadAllKeys:   
        in  a,(c)
        ld  (hl),a
        inc hl      
        
        ld  d,5
        ld  e,$ff
@DoAll: 
        srl a
        jr  c,@notset
        ld  (iy+0),e
@notset:
        inc iy
        dec d
        jr  nz,@DoAll

        ld  a,b
        sla a
        jr  nc,ExitKeyRead
        or  1
        ld  b,a
        jp  @ReadAllKeys
ExitKeyRead:
        ret




